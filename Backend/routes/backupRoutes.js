
const express = require("express");
const router = express.Router();

const { createBackup } = require("../services/backupService");
const {
  listBackups,
  downloadBackup,
} = require("../services/s3Service");

const { verifyToken, verifyAdmin } = require("../middleware/authMiddleware");

// Create a backup — admin only
router.get("/create", verifyToken, verifyAdmin, async (req, res) => {
  try {
    await createBackup();

    return res.json({
      success: true,
      message: "Backup created successfully",
    });
  } catch (error) {
    console.error("Backup creation failed:", error.message);

    return res.status(500).json({
      success: false,
      message: "Backup creation failed",
    });
  }
});

// Download a backup from S3 — admin only
router.get("/download/:file", verifyToken, verifyAdmin, async (req, res) => {
  const fileName = req.params.file;

  // Accept only backup filenames generated by the backup service
  if (
    typeof fileName !== "string" ||
    !/^backup-[\d_-]+\.sql$/.test(fileName)
  ) {
    return res.status(400).json({
      success: false,
      message: "Invalid backup filename",
    });
  }

  try {
    const backup = await downloadBackup(fileName);

    if (!backup.Body) {
      return res.status(404).json({
        success: false,
        message: "Backup not found",
      });
    }

    res.setHeader("Content-Type", "application/sql");
    res.setHeader(
      "Content-Disposition",
      `attachment; filename="${fileName}"`
    );

    backup.Body.on("error", (error) => {
      console.error("Backup download stream failed:", error.message);

      if (!res.headersSent) {
        res.status(500).json({
          success: false,
          message: "Backup download failed",
        });
      } else {
        res.destroy(error);
      }
    });

    backup.Body.pipe(res);
  } catch (error) {
    if (
      error.name === "NoSuchKey" ||
      error.name === "NotFound" ||
      error.$metadata?.httpStatusCode === 404
    ) {
      return res.status(404).json({
        success: false,
        message: "Backup not found",
      });
    }

    console.error("Backup download failed:", error.message);

    return res.status(500).json({
      success: false,
      message: "Backup download failed",
    });
  }
});

// List backups in S3 — admin only
router.get("/list", verifyToken, verifyAdmin, async (req, res) => {
  try {
    const files = await listBackups();
    return res.json(files);
  } catch (error) {
    console.error("Listing backups failed:", error.message);

    return res.status(500).json({
      success: false,
      message: "Unable to list backups",
    });
  }
});

module.exports = router;
